def write_json(name: str, data: list[dict]) -> None:
    path = OUT / name
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {path.name}: {len(data)}")


def main() -> None:
    from _extra_subjects import (
        EXTRA_BIOLOGY,
        EXTRA_CHEMISTRY,
        EXTRA_MATH,
        EXTRA_PHYSICS,
        EXTRA_SOGO,
    )

    math = mk("math", MATH + EXTRA_MATH)
    physics = mk("physics", PHYSICS + EXTRA_PHYSICS)
    chemistry = mk("chemistry", CHEMISTRY + EXTRA_CHEMISTRY)
    biology = mk("biology", BIOLOGY + EXTRA_BIOLOGY)
    sogo = mk("sogo", SOGO + EXTRA_SOGO)

    write_json("eju-math.json", math)
    write_json("eju-physics.json", physics)
    write_json("eju-chemistry.json", chemistry)
    write_json("eju-biology.json", biology)
    write_json("eju-sogo.json", sogo)

    all_subj = math + physics + chemistry + biology + sogo
    write_json("eju-subjects-all.json", all_subj)

    # Also emit TypeScript staging module (data only, not wired into app)
    def esc(s: str) -> str:
        return s.replace("\\", "\\\\").replace('"', '\\"')

    lines = [
        "/**",
        " * STAGING ONLY — not imported by the app yet.",
        " * Claude/other agents can later wire these into decks.",
        " * Fields: kanji, kana, romaji (발음), meaning, subject|level",
        " */",
        "",
        "export type StagedVocab = {",
        '  kanji: string;',
        '  kana: string;',
        '  romaji: string;',
        '  meaning: string;',
        "  subject?: string;",
        "  level?: string;",
        "};",
        "",
        f"export const ejuMathStaging: StagedVocab[] = {json.dumps(math, ensure_ascii=False, indent=2)};",
        "",
        f"export const ejuPhysicsStaging: StagedVocab[] = {json.dumps(physics, ensure_ascii=False, indent=2)};",
        "",
        f"export const ejuChemistryStaging: StagedVocab[] = {json.dumps(chemistry, ensure_ascii=False, indent=2)};",
        "",
        f"export const ejuBiologyStaging: StagedVocab[] = {json.dumps(biology, ensure_ascii=False, indent=2)};",
        "",
        f"export const ejuSogoStaging: StagedVocab[] = {json.dumps(sogo, ensure_ascii=False, indent=2)};",
        "",
    ]
    (OUT / "eju-subjects-staging.ts").write_text("\n".join(lines), encoding="utf-8")
    print("wrote eju-subjects-staging.ts")

    # JLPT TS by level (read existing JSON)
    jlpt_parts = []
    for lv in ["n5", "n4", "n3", "n2", "n1"]:
        arr = json.loads((OUT / f"jlpt-{lv}.json").read_text(encoding="utf-8"))
        # normalize keys for staging type
        staged = [
            {
                "kanji": e["kanji"],
                "kana": e["kana"],
                "romaji": e["romaji"],
                "meaning": e["meaning"],
                "level": e["level"],
            }
            for e in arr
        ]
        const = f"jlpt{lv.upper()}Staging"
        jlpt_parts.append(f"export const {const}: StagedVocab[] = {json.dumps(staged, ensure_ascii=False, indent=2)};")
        print(f"jlpt {lv}: {len(staged)}")

    header = [
        "/**",
        " * STAGING ONLY — JLPT N1–N5 from N1-N5단어 통합.pdf",
        " * Not imported by the app yet.",
        " */",
        "",
        "export type StagedVocab = {",
        "  kanji: string;",
        "  kana: string;",
        "  romaji: string;",
        "  meaning: string;",
        "  level?: string;",
        "  subject?: string;",
        "};",
        "",
    ]
    # Write separate files per level to avoid huge single file
    for lv, part in zip(["n5", "n4", "n3", "n2", "n1"], jlpt_parts):
        (OUT / f"jlpt-{lv}-staging.ts").write_text(
            "\n".join(header + [part, ""]), encoding="utf-8"
        )
        print(f"wrote jlpt-{lv}-staging.ts")

    index = """/**
 * STAGING INDEX — vocab ready for later import into the app.
 * Do not import from app seed/UI until wiring is intentional.
 *
 * Format: kanji | kana | romaji(발음) | meaning | level/subject
 *
 * Files:
 * - jlpt-n1.json … jlpt-n5.json, jlpt-all.json
 * - jlpt-n1-staging.ts … jlpt-n5-staging.ts
 * - eju-math/physics/chemistry/biology/sogo.json
 * - eju-subjects-all.json, eju-subjects-staging.ts
 */
export type { StagedVocab } from './eju-subjects-staging';
export {
  ejuMathStaging,
  ejuPhysicsStaging,
  ejuChemistryStaging,
  ejuBiologyStaging,
  ejuSogoStaging,
} from './eju-subjects-staging';
export { jlptN5Staging } from './jlpt-n5-staging';
export { jlptN4Staging } from './jlpt-n4-staging';
export { jlptN3Staging } from './jlpt-n3-staging';
export { jlptN2Staging } from './jlpt-n2-staging';
export { jlptN1Staging } from './jlpt-n1-staging';
"""
    (OUT / "index.ts").write_text(index, encoding="utf-8")
    print("wrote index.ts")
    print("TOTAL subjects", len(all_subj))


if __name__ == "__main__":
    main()
