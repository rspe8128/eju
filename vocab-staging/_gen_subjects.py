def kata_to_hira(s: str) -> str:
    out = []
    for ch in s:
        o = ord(ch)
        if 0x30A1 <= o <= 0x30F6:
            out.append(chr(o - 0x60))
        else:
            out.append(ch)
    return "".join(out)


def to_romaji(kana: str) -> str:
    s = kata_to_hira(kana)
    res = []
    i = 0
    while i < len(s):
        if s[i] == "っ" and i + 1 < len(s):
            for L in (2, 1):
                if i + 1 + L <= len(s) and s[i + 1 : i + 1 + L] in HIRA:
                    nxt = HIRA[s[i + 1 : i + 1 + L]]
                    if nxt and nxt[0].isalpha():
                        res.append(nxt[0])
                    break
            i += 1
            continue
        matched = False
        for L in (2, 1):
            chunk = s[i : i + L]
            if chunk in HIRA:
                res.append(HIRA[chunk])
                i += L
                matched = True
                break
        if not matched:
            if s[i].isascii():
                res.append(s[i])
            i += 1
    rom = "".join(res)
    return re.sub(r"n([aiueoy])", r"n'\1", rom)


def mk(subject: str, items: list[tuple[str, str, str]]) -> list[dict]:
    out = []
    seen = set()
    for kanji, kana, meaning in items:
        key = (kanji, kana)
        if key in seen:
            continue
        seen.add(key)
        out.append(
            {
                "subject": subject,
                "kanji": kanji,
                "kana": kana,
                "romaji": to_romaji(kana),
                "meaning": meaning,
            }
        )
    return out


